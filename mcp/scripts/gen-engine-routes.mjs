#!/usr/bin/env node
// Extract the Reality Engine and Perception Engine route tables from the C++
// runtime, which is the canonical definition of the HTTP surface
// (RealityEngine_CI#91), into test/fixtures/engine-routes.json.
//
// The offline MCP e2e stands a stub engine on these routes and asserts every
// tool reaches one. That check is only meaningful because the routes come
// from the engine rather than from the tool definitions being tested — a tool
// pointing at a path no engine serves has nowhere to land.
//
//   node scripts/gen-engine-routes.mjs           # write the fixture
//   node scripts/gen-engine-routes.mjs --check   # fail if stale
//
// Skips (exit 0) when the C++ source is not checked out beside this repo, so
// it does not turn a partial workspace into a build failure.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixturePath = resolve(here, '../test/fixtures/engine-routes.json');

const cppRoot =
  process.env.REALITY_ENGINE_CPP_DIR || resolve(here, '../../../RealityEngine_CPP');

const SOURCES = {
  re: resolve(cppRoot, 'src/reality_engine_server.cpp'),
  pe: resolve(cppRoot, 'src/perception_engine_server.cpp'),
};

// server.route("GET", "/api/thing/:id", ...)
const ROUTE_RE = /route\(\s*"([A-Z]+)"\s*,\s*"(\/api\/[^"]*)"/g;

function extract(file) {
  const src = readFileSync(file, 'utf8');
  const out = new Set();
  for (const m of src.matchAll(ROUTE_RE)) out.add(`${m[1]} ${m[2]}`);
  return [...out].sort();
}

const missing = Object.values(SOURCES).filter((f) => !existsSync(f));
if (missing.length) {
  process.stderr.write(
    `[gen-engine-routes] C++ engine source not found (${missing[0]}); skipping.\n` +
      `[gen-engine-routes] Set REALITY_ENGINE_CPP_DIR to regenerate.\n`
  );
  process.exit(0);
}

const generated = {
  $comment:
    'Generated by scripts/gen-engine-routes.mjs from RealityEngine_CPP. Do not edit by hand; run npm run routes:gen.',
  source: 'RealityEngine_CPP/src/{reality,perception}_engine_server.cpp',
  re: extract(SOURCES.re),
  pe: extract(SOURCES.pe),
};

const serialized = `${JSON.stringify(generated, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(fixturePath) ? readFileSync(fixturePath, 'utf8') : '';
  if (current !== serialized) {
    process.stderr.write(
      'engine-routes.json is stale. Run: npm run routes:gen\n'
    );
    process.exit(1);
  }
  process.stdout.write('engine-routes.json is up to date.\n');
  process.exit(0);
}

writeFileSync(fixturePath, serialized);
process.stdout.write(
  `engine-routes.json written (${generated.re.length} RE routes, ${generated.pe.length} PE routes).\n`
);
