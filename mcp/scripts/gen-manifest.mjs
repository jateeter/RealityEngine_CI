#!/usr/bin/env node
// Generate mcp/manifest.json from the live tool catalogue (src/tools.js) plus
// the static server descriptor below. Keeping the manifest derived means the
// tool list can never drift from what the server actually registers.
//
//   node scripts/gen-manifest.mjs            # write manifest.json
//   node scripts/gen-manifest.mjs --check    # exit 1 if manifest.json is stale
//
// Run from the mcp/ directory (npm run manifest:gen / manifest:check).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { TOOLS } from '../src/tools.js';
import { settings } from '../src/config.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const MANIFEST_PATH = join(__dirname, '..', 'manifest.json');

// Static server descriptor — the parts that are not derivable from the catalogue.
const descriptor = {
  name: settings.serverName,
  displayName: 'RealityEngine MCP Gateway',
  version: settings.serverVersion,
  description:
    'Model Context Protocol gateway packaging the RealityEngine Reality Engine (RE) and Perception Engine (PE) HTTP surfaces — CPP, LSP, and Scala runtimes — as MCP tools and resources.',
  vendor: 'EnergyOS / RealityEngine',
  homepage: 'https://github.com/EnergyOS/RealityEngine_CI',
  license: 'UNLICENSED',
  transports: {
    stdio: { command: 'node', args: ['bin/realityengine-mcp.js'] },
    streamableHttp: { endpoint: '/mcp', defaultPort: settings.httpPort },
  },
  discovery: {
    registry: 'RE_REGISTRY_URL',
    fallback: ['RE_URL', 'PE_URL'],
    note: 'Registry-aware: multiple runtimes (cpp/lsp/scala) may be live; tools accept an optional `instance` arg (id or runtime).',
  },
  policy: {
    readOnlyByDefault: true,
    mutationOptIn: ['RE_MCP_ALLOW_MUTATION', 'RE_MCP_ALLOWED_TOOLS'],
  },
  resources: [
    { uri: 'realityengine://instances', description: 'Live RE/PE instances.' },
    {
      uri: 'realityengine://openapi/{file}',
      description: 'Generated OpenAPI 3.1 specs (cpp|lsp|scala × re|pe).',
    },
  ],
};

function buildManifest() {
  return {
    _generated: 'Generated by scripts/gen-manifest.mjs from src/tools.js — do not edit by hand.',
    ...descriptor,
    tools: TOOLS.map((t) => ({ name: t.name, target: t.target, mutating: t.mutating })),
  };
}

const next = JSON.stringify(buildManifest(), null, 2) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(MANIFEST_PATH, 'utf8');
  } catch {
    /* missing -> stale */
  }
  if (current !== next) {
    process.stderr.write('manifest.json is stale. Run: npm run manifest:gen\n');
    process.exit(1);
  }
  process.stdout.write('manifest.json is up to date.\n');
} else {
  writeFileSync(MANIFEST_PATH, next);
  process.stdout.write(`wrote ${MANIFEST_PATH} (${TOOLS.length} tools)\n`);
}
