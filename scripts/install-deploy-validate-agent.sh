#!/usr/bin/env bash
# Install the launchd agent that runs scripts/deploy-validate-scheduled.sh
# (DEPLOYMENT_VALIDATION_ROADMAP.md, Phase 5).
#
#   scripts/install-deploy-validate-agent.sh                 # print the plist, change nothing
#   scripts/install-deploy-validate-agent.sh --execute       # write it and reload the agent
#   scripts/install-deploy-validate-agent.sh --interval 21600 --execute
#
# The plist used to be written by hand, and two things in it went wrong:
#
#   - It launched `/bin/bash -lc <script>`. A login shell runs the user's
#     profile under macOS bash 3.2 before the script can re-exec into bash 5,
#     so every run logged sdkman's `${candidate_name^^}: bad substitution`, and
#     path_helper reordered PATH ahead of what the plist set (the Node 22
#     incident in deploy-validate-scheduled.sh).
#   - Its PATH named an absolute nvm Node, v26.8.2, which nothing moved when
#     scripts/advance-node.sh advanced the minor to 26.12.
#
# So the agent runs bash 5 directly, no login shell, and its PATH names no Node:
# the scheduled script establishes Node from CI's .nvmrc through
# scripts/lib/node-env.sh, the same as every other Node-running script. Java and
# sbt come from sdkman's `current` links, which follow `sdk default`.
#
# Without --execute this prints the plist on stdout and the actions on stderr.
set -euo pipefail

LABEL="org.energyos.realityengine.deploy-validate"
CI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASH5="${DEPLOY_VALIDATE_BASH:-/opt/homebrew/bin/bash}"
INTERVAL=604800   # weekly; it ran every 6h (21600) until 2026-09-13
EXECUTE=false

usage() { sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --execute) EXECUTE=true; shift ;;
    --interval) INTERVAL="${2:-}"; shift 2 ;;
    --interval=*) INTERVAL="${1#*=}"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "install-deploy-validate-agent: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

case "$INTERVAL" in
  ''|*[!0-9]*) echo "install-deploy-validate-agent: --interval must be whole seconds, got '$INTERVAL'" >&2; exit 2 ;;
esac
if [ "$INTERVAL" -lt 3600 ]; then
  echo "install-deploy-validate-agent: --interval $INTERVAL is under an hour; a run takes longer than that" >&2
  exit 2
fi

AGENT_PATH="$HOME/.local/bin:$HOME/.sdkman/candidates/sbt/current/bin:$HOME/.sdkman/candidates/java/current/bin:/opt/homebrew/bin:/opt/homebrew/sbin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
OUT_DIR="$CI_DIR/.deploy-validate/scheduled"

xml_escape() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g' <<< "$1"; }

render_plist() {
  local java_home=""
  [ -d "$HOME/.sdkman/candidates/java/current" ] && java_home="$HOME/.sdkman/candidates/java/current"
  cat <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by RealityEngine_CI/scripts/install-deploy-validate-agent.sh; regenerate, do not edit. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>$(xml_escape "$BASH5")</string>
    <string>$(xml_escape "$CI_DIR/scripts/deploy-validate-scheduled.sh")</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>HOME</key>
    <string>$(xml_escape "$HOME")</string>
    <key>PATH</key>
    <string>$(xml_escape "$AGENT_PATH")</string>
PLIST
  if [ -n "$java_home" ]; then
    cat <<PLIST
    <key>JAVA_HOME</key>
    <string>$(xml_escape "$java_home")</string>
PLIST
  fi
  cat <<PLIST
  </dict>
  <key>WorkingDirectory</key>
  <string>$(xml_escape "$CI_DIR")</string>
  <key>StartInterval</key>
  <integer>$INTERVAL</integer>
  <key>RunAtLoad</key>
  <false/>
  <key>ProcessType</key>
  <string>Background</string>
  <key>LowPriorityIO</key>
  <true/>
  <key>StandardOutPath</key>
  <string>$(xml_escape "$OUT_DIR/launchd.out.log")</string>
  <key>StandardErrorPath</key>
  <string>$(xml_escape "$OUT_DIR/launchd.err.log")</string>
</dict>
</plist>
PLIST
}

PLIST_FILE="$HOME/Library/LaunchAgents/$LABEL.plist"

if [ "$EXECUTE" != true ]; then
  render_plist
  {
    echo "install-deploy-validate-agent: dry run, nothing changed. With --execute it would:"
    echo "  write   $PLIST_FILE (backing up an existing one beside it)"
    echo "  reload  gui/$(id -u)/$LABEL (bootout, then bootstrap)"
  } >&2
  exit 0
fi

[ -x "$BASH5" ] || { echo "install-deploy-validate-agent: $BASH5 is not executable; install bash 5 (brew install bash) or set DEPLOY_VALIDATE_BASH" >&2; exit 1; }
"$BASH5" -c '[ "${BASH_VERSINFO[0]}" -ge 5 ]' || { echo "install-deploy-validate-agent: $BASH5 is not bash 5" >&2; exit 1; }

mkdir -p "$(dirname "$PLIST_FILE")" "$OUT_DIR"
tmp="$(mktemp)"
render_plist > "$tmp"
plutil -lint "$tmp" >/dev/null
if [ -f "$PLIST_FILE" ]; then
  cp -p "$PLIST_FILE" "$PLIST_FILE.bak-$(date -u +%Y%m%dT%H%M%SZ)"
fi
mv "$tmp" "$PLIST_FILE"
chmod 644 "$PLIST_FILE"

domain="gui/$(id -u)"
launchctl bootout "$domain/$LABEL" 2>/dev/null || true
launchctl bootstrap "$domain" "$PLIST_FILE"
echo "install-deploy-validate-agent: installed $PLIST_FILE and loaded $domain/$LABEL (every ${INTERVAL}s)"
