#!/usr/bin/env python3
"""The OpenSSL fronts for the Go observability services (RealityEngine_CI#729, #730).

Loki, Prometheus and Grafana are Go programs, and Go's crypto/tls does not let a
server choose its TLS 1.3 cipher suites: TLS_AES_128_GCM_SHA256 is always
negotiable, outside the profile. So on the lane each listens only on its own
container's loopback, and an nginx (OpenSSL) sidecar in the same network
namespace serves its public port at the profile (owner, 2026-11-12):

- TLS 1.3 only, the profile's suites and groups (config/transport-profile.json);
- a lane client certificate required, checked against the lane CA and CRL,
  except on Grafana's browser port (server TLS: a user-facing port);
- the hop to the service on the container's loopback is TLS 1.3 too, and the
  front offers only the profile's suites on it, so nothing outside the profile
  is negotiated there either.

Writes <out-dir>/<service>.conf for loki, prometheus and grafana. Paths inside
the front container: /run/re-tls/service/{chain,key}.pem (the service's own
certificate), /run/re-tls/ca.crt and /run/re-tls/ca.crl.

Usage: obs_front_conf.py <out-dir>
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

CI_DIR = Path(__file__).resolve().parents[2]
TLS_DIR = "/run/re-tls"

# service -> (inner port on 127.0.0.1, [(public port, client certificate required)], TLS name)
FRONTS: dict[str, tuple[int, list[tuple[int, bool]], str]] = {
    "loki": (3101, [(3100, True)], "loki"),
    "prometheus": (9091, [(9090, True)], "prometheus"),
    # 3000: the browser's (published as 3002); 3443: tls-proxy's, on the lane's mTLS.
    "grafana": (3001, [(3000, False), (3443, True)], "grafana"),
}


def server(port: int, mtls: bool, inner: int, name: str, suites: str, groups: str) -> str:
    client = (f"        ssl_verify_client      on;\n"
              f"        ssl_client_certificate {TLS_DIR}/ca.crt;\n"
              f"        ssl_crl                {TLS_DIR}/ca.crl;\n") if mtls else ""
    return f"""    server {{
        listen {port} ssl;
        ssl_certificate     {TLS_DIR}/service/chain.pem;
        ssl_certificate_key {TLS_DIR}/service/key.pem;
        ssl_protocols       TLSv1.3;
        ssl_conf_command    Ciphersuites {suites};
        ssl_ecdh_curve      {groups};
        ssl_session_tickets off;
{client}        client_max_body_size 0;

        location / {{
            proxy_pass                    https://127.0.0.1:{inner};
            proxy_ssl_verify              on;
            proxy_ssl_trusted_certificate {TLS_DIR}/ca.crt;
            proxy_ssl_name                {name};
            proxy_ssl_protocols           TLSv1.3;
            proxy_ssl_conf_command        Ciphersuites {suites};
            proxy_http_version            1.1;
            proxy_set_header              Host $host;
            proxy_set_header              Upgrade $http_upgrade;
            proxy_set_header              Connection $connection_upgrade;
            proxy_set_header              X-Forwarded-Proto https;
            proxy_read_timeout            3600s;
            proxy_buffering               off;
        }}
    }}
"""


def conf(service: str, suites: str, groups: str) -> str:
    inner, listeners, name = FRONTS[service]
    servers = "".join(server(p, m, inner, name, suites, groups) for p, m in listeners)
    return f"""# Generated by scripts/lib/obs_front_conf.py (RealityEngine_CI#729): the OpenSSL
# front for {service}, which listens on 127.0.0.1:{inner} in this network namespace.
worker_processes 1;
pid /tmp/nginx.pid;
events {{ worker_connections 256; }}
http {{
    access_log off;
    client_body_temp_path /tmp/client_body;
    proxy_temp_path       /tmp/proxy;
    fastcgi_temp_path     /tmp/fastcgi;
    uwsgi_temp_path       /tmp/uwsgi;
    scgi_temp_path        /tmp/scgi;
    map $http_upgrade $connection_upgrade {{ default upgrade; '' close; }}
{servers}}}
"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    out = Path(sys.argv[1])
    tls = json.loads((CI_DIR / "config" / "transport-profile.json").read_text())["tls"]
    suites = ":".join(tls["cipherSuites"])
    groups = ":".join(tls["keyExchangeGroups"]["preferred"] + tls["keyExchangeGroups"]["fallback"])
    out.mkdir(parents=True, exist_ok=True)
    for service in FRONTS:
        (out / f"{service}.conf").write_text(conf(service, suites, groups))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
