#!/usr/bin/env python3
"""Compose config/extension-corpus.txt from config/extension-corpus.json.

The extension corpus is the regression corpus plus the machine-factory
candidates that sit above the corpus vector budget (RealityEngine_Machines
GOV-SD-12). It is written, never hand-edited, so its regression half cannot
drift from config/regression-corpus.txt.

  --write   rewrite config/extension-corpus.txt
  --check   exit 1 if it is not what --write would produce (default)

With the RealityEngine_Machines checkout beside this repository, --check also
confirms that every candidate file exists in its package. Without one it says
so and checks the composition only.

Candidates are listed as domains/<package>/<file>, so they materialize under
machines/domains/<package>/. scripts/materialize-machine-corpus.sh finds them
by basename under RealityEngine_Machines/machine_factory/domains, which
startUniverse.sh passes as an extra root.
"""
import argparse
import json
import pathlib
import sys

CI = pathlib.Path(__file__).resolve().parent.parent
CONFIG = CI / "config"
SPEC = CONFIG / "extension-corpus.json"
OUT = CONFIG / "extension-corpus.txt"
MACHINES = CI.parent / "RealityEngine_Machines"


def entries(path):
    out = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def compose():
    spec = json.loads(SPEC.read_text())
    lines = [
        "# Extension corpus: GENERATED by scripts/write-extension-corpus.py from",
        "# config/extension-corpus.json. Do not edit; change the JSON and run --write.",
        "#",
        "# The regression corpus, then the machine-factory candidates above the corpus",
        "# vector budget (16944) that the shared extension corpus carries",
        "# (RealityEngine_Machines GOV-SD-12, MACHINE_CONCEPT section 9.3).",
        "# Boot it with --machine-corpus=extension.",
    ]
    seen = set()
    for inc in spec["includes"]:
        lines += ["", f"# --- {inc} ---"]
        for e in entries(CONFIG / inc):
            if e in seen:
                raise SystemExit(f"duplicate entry {e} (from {inc})")
            seen.add(e)
            lines.append(e)
    for c in spec["candidates"]:
        lines += ["", f"# --- candidates: {c['package']} ({c['status']}, band {c['band']}) ---"]
        for m in c["machines"]:
            e = f"domains/{c['package']}/{m}"
            base = pathlib.PurePosixPath(e).name
            if base in {pathlib.PurePosixPath(x).name for x in seen}:
                raise SystemExit(f"candidate {base} collides with an included entry")
            seen.add(e)
            lines.append(e)
    for d in spec.get("deferred", []):
        lines += ["", f"# deferred: {d['package']}: {d['why']}"]
    return "\n".join(lines) + "\n", spec


def check_files(spec):
    if not MACHINES.is_dir():
        print("note: RealityEngine_Machines is not beside this checkout; candidate files not checked")
        return []
    missing = []
    for c in spec["candidates"]:
        src = CI.parent / c["source"]
        for m in c["machines"]:
            if not (src / m).is_file():
                missing.append(f"{c['source']}/{m}")
        if src.is_dir():
            extra = sorted(p.name for p in src.glob("*.json") if p.name not in c["machines"])
            missing += [f"{c['source']}/{e} (in the package, not listed)" for e in extra]
    return missing


def main():
    ap = argparse.ArgumentParser(description="Compose config/extension-corpus.txt from config/extension-corpus.json.")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text, spec = compose()
    problems = check_files(spec)
    if a.write:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(CI)} ({sum(1 for x in text.splitlines() if x and not x.startswith('#'))} machines)")
    elif not OUT.is_file() or OUT.read_text() != text:
        problems.append("config/extension-corpus.txt is not current: run scripts/write-extension-corpus.py --write")
    for p in problems:
        print(f"FAIL: {p}")
    if not problems and not a.write:
        print("extension-corpus: ok")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
