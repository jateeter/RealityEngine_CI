#!/usr/bin/env python3
"""Compose the extension corpus manifest from config/extension-corpus.json.

The extension corpus is the regression corpus plus the machine-factory
candidates that sit above the corpus vector budget (RealityEngine_Machines
GOV-SD-12). It is written, never hand-edited, so its regression half cannot
drift from config/regression-corpus.txt.

  --write          rewrite config/extension-corpus.txt (the committed snapshot)
  --out PATH       compose to PATH instead (startUniverse.sh does this at boot)
  --check          the gate (default): exit 1 only if the regression half of
                   config/extension-corpus.txt differs from its includes

**Machine-factory work in progress never fails a gate** (owner, 2026-11-27).
A package's candidates are its machines/*.json as they stand when composed, so
a candidate added, renamed or removed in the factory boots as it now is: the
harness composes the manifest at boot with --out. --check reports a committed
snapshot whose candidate block differs from the package as a note, never as a
failure, and a package that cannot be read (no RealityEngine_Machines beside
this checkout) is a note too. Candidates are outside the cesgen registry's
check until admitted (RealityEngine_Machines build-ces-contract-registry.py).

Candidates are listed as domains/<package>/<file>, so they materialize under
machines/domains/<package>/. scripts/materialize-machine-corpus.sh finds them
by basename under RealityEngine_Machines/machine_factory/domains, which
startUniverse.sh passes as an extra root.
"""
import argparse
import json
import pathlib
import sys

CI = pathlib.Path(__file__).resolve().parent.parent
CONFIG = CI / "config"
SPEC = CONFIG / "extension-corpus.json"
OUT = CONFIG / "extension-corpus.txt"
WORKSPACE = CI.parent
CANDIDATES_MARK = "# --- candidates: "


def entries(path):
    out = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def package_machines(c, notes):
    """The package's machines/*.json as they stand, else the spec's last-known list."""
    src = WORKSPACE / c["source"]
    if src.is_dir():
        return sorted(p.name for p in src.glob("*.json"))
    notes.append(f"{c['source']} is not readable here; composed from the spec's last-known list")
    return sorted(c.get("lastKnown", []))


def compose(notes):
    spec = json.loads(SPEC.read_text())
    head = [
        "# Extension corpus: GENERATED by scripts/write-extension-corpus.py from",
        "# config/extension-corpus.json. Do not edit; change the JSON and run --write.",
        "#",
        "# The regression corpus, then the machine-factory candidates above the corpus",
        "# vector budget (16944) that the shared extension corpus carries",
        "# (RealityEngine_Machines GOV-SD-12, MACHINE_CONCEPT section 9.3).",
        "# Boot it with --machine-corpus=extension: the harness composes this list",
        "# afresh at boot, so a candidate boots as it stands in its package.",
    ]
    regression, seen = [], set()
    for inc in spec["includes"]:
        regression += ["", f"# --- {inc} ---"]
        for e in entries(CONFIG / inc):
            if e in seen:
                raise SystemExit(f"duplicate entry {e} (from {inc})")
            seen.add(e)
            regression.append(e)
    bases = {pathlib.PurePosixPath(x).name for x in seen}
    cand = []
    for c in spec["candidates"]:
        cand += ["", f"{CANDIDATES_MARK}{c['package']} ({c['status']}, band {c['band']}) ---"]
        for m in package_machines(c, notes):
            if m in bases:
                raise SystemExit(f"candidate {m} collides with an included entry")
            cand.append(f"domains/{c['package']}/{m}")
    tail = []
    for d in spec.get("deferred", []):
        tail += ["", f"# deferred: {d['package']}: {d['why']}"]
    return head, regression, cand, tail


def render(head, regression, cand, tail):
    return "\n".join(head + regression + cand + tail) + "\n"


def regression_half(text):
    """Everything before the first candidates block: the part that gates."""
    out = []
    for line in text.splitlines():
        if line.startswith(CANDIDATES_MARK):
            break
        out.append(line)
    return "\n".join(out).rstrip("\n")


def main():
    ap = argparse.ArgumentParser(description="Compose the extension corpus manifest.")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--out", type=pathlib.Path)
    a = ap.parse_args()
    notes = []
    head, regression, cand, tail = compose(notes)
    text = render(head, regression, cand, tail)
    count = sum(1 for x in text.splitlines() if x and not x.startswith("#"))
    if a.write or a.out:
        dest = a.out or OUT
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
        print(f"wrote {dest} ({count} machines)")
        for n in notes:
            print(f"note: {n}")
        return 0
    if not OUT.is_file():
        print("FAIL: config/extension-corpus.txt is missing: run scripts/write-extension-corpus.py --write")
        return 1
    committed = OUT.read_text()
    if regression_half(committed) != regression_half(text):
        print("FAIL: the regression half of config/extension-corpus.txt is not current: "
              "run scripts/write-extension-corpus.py --write")
        return 1
    if committed != text:
        notes.append("the committed candidate snapshot differs from the packages as they stand; "
                     "not gating (the harness composes at boot). Refresh with --write when convenient")
    for n in notes:
        print(f"note: {n}")
    print("extension-corpus: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
